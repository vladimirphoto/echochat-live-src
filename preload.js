const { contextBridge, ipcRenderer } = require('electron');

const on = (channel) => (cb) => ipcRenderer.on(channel, (_e, data) => cb(data));

contextBridge.exposeInMainWorld('echo', {
  connect: (name) => ipcRenderer.invoke('tt:connect', name),
  disconnect: () => ipcRenderer.invoke('tt:disconnect'),
  synth: (opts) => ipcRenderer.invoke('tts:synth', opts),
  voices: () => ipcRenderer.invoke('tts:voices'),
  version: () => ipcRenderer.invoke('app:version'),
  checkUpdate: () => ipcRenderer.invoke('upd:check'),
  installUpdate: () => ipcRenderer.invoke('upd:install'),
  onUpdateProgress: on('upd:progress'),
  appSettings: () => ipcRenderer.invoke('app:settings:get'),
  appSettingsSet: (patch) => ipcRenderer.invoke('app:settings:set', patch),
  closeAnswer: (a) => ipcRenderer.invoke('app:close-answer', a),
  onAskClose: on('app:ask-close'),
  trayState: (st) => ipcRenderer.send('tray:state', st),
  onTraySet: on('tray:set'),
  onTraySkip: on('tray:skip'),
  twConnect: (name) => ipcRenderer.invoke('tw:connect', name),
  twDisconnect: () => ipcRenderer.invoke('tw:disconnect'),
  onTwChat: on('tw:chat'),
  onTwStatus: on('tw:status'),
  onTwViewers: on('tw:viewers'),
  widgetUrl: () => ipcRenderer.invoke('widget:url'),
  widgetLink: (mode) => ipcRenderer.invoke('widget:link', mode),
  widgetCheck: () => ipcRenderer.invoke('widget:check'),
  widgetSet: (s) => ipcRenderer.invoke('widget:set', s),
  widgetTest: () => ipcRenderer.invoke('widget:test'),
  widgetClear: () => ipcRenderer.invoke('widget:clear'),
  likesSet: (s) => ipcRenderer.invoke('likes:set', s),
  likesTest: () => ipcRenderer.invoke('likes:test'),
  likesClear: () => ipcRenderer.invoke('likes:clear'),
  likesUrl: () => ipcRenderer.invoke('likes:url'),
  likesLink: () => ipcRenderer.invoke('likes:link'),
  donateSet: (s) => ipcRenderer.invoke('donate:set', s),
  donateTest: () => ipcRenderer.invoke('donate:test'),
  donateUrl: () => ipcRenderer.invoke('donate:url'),
  donateLink: () => ipcRenderer.invoke('donate:link'),
  kaspiState: () => ipcRenderer.invoke('kaspi:state'),
  kaspiShortcut: () => ipcRenderer.invoke('kaspi:shortcut'),
  kaspiSample: (i) => ipcRenderer.invoke('kaspi:sample', i),
  engStatus: () => ipcRenderer.invoke('eng:status'),
  engSet: (o) => ipcRenderer.invoke('eng:set', o),
  engInstall: (id) => ipcRenderer.invoke('eng:install', id),
  onEngProgress: (cb) => ipcRenderer.on('eng:progress', (_e, d) => cb(d)),
  kaspiProbe: () => ipcRenderer.invoke('kaspi:probe'),
  onDonate: on('kaspi:donate'),
  onKaspiLog: on('kaspi:log'),
  onKaspiRelay: on('kaspi:relay'),
  licState: () => ipcRenderer.invoke('lic:state'),
  licRefresh: () => ipcRenderer.invoke('lic:refresh'),
  licActivate: (key) => ipcRenderer.invoke('lic:activate', key),
  licDeactivate: () => ipcRenderer.invoke('lic:deactivate'),
  licPurchase: () => ipcRenderer.invoke('lic:purchase'),
  onLic: on('lic:state'),
  netCheck: () => ipcRenderer.invoke('net:check'),
  netState: () => ipcRenderer.invoke('net:state'),
  onNet: on('net:status'),
  onChat: on('tt:chat'),
  onGift: on('tt:gift'),
  onFollow: on('tt:follow'),
  onLike: on('tt:like'),
  onViewers: on('tt:viewers'),
  onStatus: on('tt:status'),
  onError: on('tt:error'),
});
